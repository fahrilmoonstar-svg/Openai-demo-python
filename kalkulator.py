#KALKULATOR SEDERHANA PYTHON

#input user
a = int(input("Angka A : "))
b = int(input("Angka B : "))

#Rumus
tambah = a + b
kurang = a - b
kali = a * b
bagi = a / b

#output / hasil
print(f"Hasil {a} + {b} = {tambah}")
print(f"Hasil {a} - {b} = {kurang}")
print(f"Hasil {a} * {b} = {kali}")
print(f"Hasil {a} / {b} = {bagi}")